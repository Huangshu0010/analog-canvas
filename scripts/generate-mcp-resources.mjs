// Generates apps/mcp-server/src/resources.generated.ts from
// docs/agent/resource-manifest.json. Repo sources are read as files; kit
// sources come from the built @icm/agent-adapter kit payload, so both MCP
// Resources and the HTTP Kit project from the same declared sources.
//
// Usage:
//   pnpm mcp:resources          (write)
//   pnpm mcp:resources:check    (fail if stale)
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { pathToFileURL, fileURLToPath } from "node:url";
import prettier from "prettier";

const repoRoot = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  "..",
);
const manifestPath = path.join(repoRoot, "docs/agent/resource-manifest.json");
const outputPath = path.join(
  repoRoot,
  "apps/mcp-server/src/resources.generated.ts",
);
const kitModulePath = path.join(
  repoRoot,
  "packages/agent-adapter/dist/agent-kit.js",
);

const knownProjections = new Set([
  "mcp-resources",
  "http-kit",
  "codex-fallback",
]);

function fail(message) {
  console.error(`generate-mcp-resources: ${message}`);
  process.exit(1);
}

function validateManifest(manifest) {
  if (manifest.format !== "icm-agent-resource-manifest-v1") {
    fail(`unexpected manifest format: ${manifest.format}`);
  }
  const uris = new Set();
  for (const resource of manifest.resources) {
    if (!resource.uri?.startsWith("analog-canvas://")) {
      fail(`resource URI must use the analog-canvas scheme: ${resource.uri}`);
    }
    if (uris.has(resource.uri)) fail(`duplicate resource URI: ${resource.uri}`);
    uris.add(resource.uri);
    for (const projection of resource.projections ?? []) {
      if (!knownProjections.has(projection)) {
        fail(`unknown projection "${projection}" on ${resource.uri}`);
      }
      if (projection === "http-kit" && resource.source.kind !== "kit") {
        fail(
          `${resource.uri} projects to http-kit but its source is not a kit file`,
        );
      }
    }
    if (!["repo", "kit"].includes(resource.source.kind)) {
      fail(`unknown source kind on ${resource.uri}`);
    }
  }
}

async function readRepoSource(resource) {
  const relative = resource.source.path;
  if (
    !relative ||
    path.isAbsolute(relative) ||
    relative.split(path.sep).includes("..")
  ) {
    fail(`unsafe repo source path on ${resource.uri}: ${relative}`);
  }
  const absolute = path.join(repoRoot, relative);
  if (!absolute.startsWith(repoRoot + path.sep)) {
    fail(`repo source escapes the repository on ${resource.uri}`);
  }
  try {
    return await readFile(absolute, "utf8");
  } catch {
    fail(`missing repo source for ${resource.uri}: ${relative}`);
  }
}

async function main() {
  const check = process.argv.includes("--check");
  const manifest = JSON.parse(await readFile(manifestPath, "utf8"));
  validateManifest(manifest);

  const { agentOperatingKit } = await import(pathToFileURL(kitModulePath).href);
  const kitFiles = new Map(
    agentOperatingKit.files.map((f) => [f.path, f.content]),
  );

  const resources = [];
  for (const resource of manifest.resources) {
    if (!(resource.projections ?? []).includes("mcp-resources")) continue;
    let text;
    if (resource.source.kind === "repo") {
      text = await readRepoSource(resource);
    } else {
      text = kitFiles.get(resource.source.path);
      if (text === undefined) {
        fail(
          `kit does not contain ${resource.source.path} required by ${resource.uri}`,
        );
      }
    }
    resources.push({
      uri: resource.uri,
      name: resource.name,
      description: resource.description,
      mimeType: resource.mimeType,
      text,
    });
  }

  const source = `// Generated by scripts/generate-mcp-resources.mjs from
// docs/agent/resource-manifest.json. Do not edit.
export const MCP_RESOURCE_MANIFEST_FORMAT = ${JSON.stringify(manifest.format)};
export const MCP_RESOURCE_MANIFEST_VERSION = ${manifest.version};
export interface McpResourceDocument {
  uri: string;
  name: string;
  description: string;
  mimeType: string;
  text: string;
}
export const mcpResources: readonly McpResourceDocument[] = ${JSON.stringify(resources)};
`;

  const formatted = await prettier.format(source, {
    parser: "typescript",
    printWidth: 80,
  });
  const stamped = formatted.endsWith("\n") ? formatted : `${formatted}\n`;

  await mkdir(path.dirname(outputPath), { recursive: true });
  const existing = await readFile(outputPath, "utf8").catch(() => null);
  if (existing === stamped) {
    console.log("generate-mcp-resources: up to date");
    return;
  }
  if (check) {
    fail(
      "apps/mcp-server/src/resources.generated.ts is stale; run pnpm mcp:resources",
    );
  }
  await writeFile(outputPath, stamped, "utf8");
  console.log(
    `generate-mcp-resources: wrote ${path.relative(repoRoot, outputPath)}`,
  );
}

await main();
